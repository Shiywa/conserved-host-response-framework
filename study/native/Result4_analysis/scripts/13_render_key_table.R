library(openxlsx)
library(jsonlite)
args <- commandArgs(trailingOnly=TRUE)
out <- if(length(args)) args[[1]] else file.path(Sys.getenv('CRRM_RESOURCE_ROOT'),"CRRM_revision_work/Result4")
spec <- fromJSON(file.path(out,'reports/table5_spec.json'))
d <- read.csv(file.path(out,'reports/TableS5_key_cellular_results.csv'),check.names=FALSE,stringsAsFactors=FALSE,na.strings=c('','NA','NaN'),fileEncoding='UTF-8')
stopifnot(nrow(d)==spec$rows,ncol(d)==16)
class(d[['Source link']]) <- 'hyperlink'
wb <- createWorkbook(creator='Liu et al.');s<-spec$sheet;addWorksheet(wb,s,gridLines=FALSE)
modifyBaseFont(wb,fontName='Arial',fontSize=10)
writeData(wb,s,spec$title,startRow=1,colNames=FALSE);mergeCells(wb,s,cols=1:ncol(d),rows=1)
addStyle(wb,s,createStyle(fontSize=12,textDecoration='bold',fontColour='#FFFFFF',fgFill='#173E56',valign='center',wrapText=TRUE),rows=1,cols=1:ncol(d),gridExpand=TRUE)
writeData(wb,s,d,startRow=2,colNames=TRUE,keepNA=FALSE,headerStyle=createStyle(textDecoration='bold',fgFill='#DCE9EF',halign='center',valign='center',wrapText=TRUE,border='Bottom'))
addStyle(wb,s,createStyle(valign='top',wrapText=TRUE),rows=3:(nrow(d)+2),cols=1:ncol(d),gridExpand=TRUE,stack=TRUE)
addStyle(wb,s,createStyle(numFmt='0'),rows=3:(nrow(d)+2),cols=5:8,gridExpand=TRUE,stack=TRUE)
addStyle(wb,s,createStyle(numFmt='0.0000'),rows=3:(nrow(d)+2),cols=9:11,gridExpand=TRUE,stack=TRUE)
addStyle(wb,s,createStyle(numFmt='0.000E+00'),rows=3:(nrow(d)+2),cols=12:14,gridExpand=TRUE,stack=TRUE)
setRowHeights(wb,s,rows=1,heights=32);setRowHeights(wb,s,rows=2,heights=32)
setRowHeights(wb,s,rows=3:(nrow(d)+2),heights=42)
setColWidths(wb,s,cols=1:16,widths=c(25,29,44,26,11,12,13,13,13,13,13,13,13,13,68,55))
freezePane(wb,s,firstActiveRow=3,firstActiveCol=1);addFilter(wb,s,rows=2,cols=1:ncol(d))
starts<-which(!duplicated(d$Analysis))+2
addStyle(wb,s,createStyle(border='Top',borderColour='#668899'),rows=starts,cols=1:ncol(d),gridExpand=TRUE,stack=TRUE)
setHeaderFooter(wb,s,header=c('', 'Liu et al. | Supplementary Table S5',''),footer=c('','Page &P of &N',''))
pageSetup(wb,s,orientation='landscape',paperSize=9,fitToWidth=1,fitToHeight=0)
dest<-file.path(out,'reports/TableS5_CRRM细胞定位.xlsx');saveWorkbook(wb,dest,overwrite=TRUE)
stopifnot(length(getSheetNames(dest))==1,nrow(read.xlsx(dest,startRow=2,check.names=FALSE))==nrow(d))
cat('PASS: one sheet;',nrow(d),'rows;title row1;header/filter row2;freeze first2 rows\n')
