suppressPackageStartupMessages(library(openxlsx))
a<-commandArgs(trailingOnly=FALSE);s<-sub('^--file=','',a[grepl('^--file=',a)]);OUT<-file.path(Sys.getenv('CRRM_WORKSPACE'),'Result6_analysis')
x<-read.csv(file.path(OUT,'reports/TableS7_key_results.csv'),check.names=FALSE,stringsAsFactors=FALSE)
wb<-createWorkbook(creator='Liu et al.');addWorksheet(wb,'Key results')
writeData(wb,'Key results','Table S7. CRRM responses to host-directed perturbations and interpretation checks',startRow=1,startCol=1,colNames=FALSE)
mergeCells(wb,'Key results',cols=seq_len(ncol(x)),rows=1)
writeData(wb,'Key results',x,startRow=2,withFilter=TRUE,keepNA=FALSE)
title<-createStyle(fontName='Arial',fontSize=12,textDecoration='bold',fontColour='#173E56',wrapText=TRUE,valign='center')
header<-createStyle(fontName='Arial',fontSize=10,textDecoration='bold',fgFill='#E8F0F4',wrapText=TRUE,valign='center',border='Bottom')
normal<-createStyle(fontName='Arial',fontSize=10,wrapText=TRUE,valign='top')
addStyle(wb,'Key results',normal,rows=3:(nrow(x)+2),cols=seq_len(ncol(x)),gridExpand=TRUE)
addStyle(wb,'Key results',title,rows=1,cols=1)
addStyle(wb,'Key results',header,rows=2,cols=seq_len(ncol(x)),gridExpand=TRUE)
num<-createStyle(numFmt='0.000000');pv<-createStyle(numFmt='0.00E+00');cnt<-createStyle(numFmt='0')
for(k in c('Estimate','Lower / minimum','Upper / maximum'))addStyle(wb,'Key results',num,rows=3:(nrow(x)+2),cols=match(k,names(x)),gridExpand=TRUE,stack=TRUE)
for(k in c('BH P','Exact P','Exact BH P'))addStyle(wb,'Key results',pv,rows=3:(nrow(x)+2),cols=match(k,names(x)),gridExpand=TRUE,stack=TRUE)
for(k in c('n case','n reference'))addStyle(wb,'Key results',cnt,rows=3:(nrow(x)+2),cols=match(k,names(x)),gridExpand=TRUE,stack=TRUE)
setColWidths(wb,'Key results',cols=1:ncol(x),widths=c(22,37,42,28,13,16,16,13,13,13,10,12,65))
setRowHeights(wb,'Key results',rows=1,heights=32);setRowHeights(wb,'Key results',rows=2,heights=32);setRowHeights(wb,'Key results',rows=3:(nrow(x)+2),heights=42)
freezePane(wb,'Key results',firstActiveRow=3,firstActiveCol=3)
saveWorkbook(wb,file.path(OUT,'reports/TableS7_宿主干预.xlsx'),overwrite=TRUE)
z<-read.xlsx(file.path(OUT,'reports/TableS7_宿主干预.xlsx'),startRow=2,check.names=FALSE)
stopifnot(nrow(z)==nrow(x),ncol(z)==ncol(x));cat('TableS7:1sheet,',nrow(x),'rows; title row1, headers row2, frozen first2rows.\n')
